  if jsonb_typeof(d -> 'cc_recipients') = 'array' then new.cc_recipients := d -> 'cc_recipients'; end if;
  new.attachments := coalesce(new.attachments, '[]');
  new.cc_recipients := coalesce(new.cc_recipients, '[]');
  return new;
end $$;

