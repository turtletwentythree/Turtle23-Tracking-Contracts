alter table public.contract_logs enable row level security;
alter table public.due_date_requests enable row level security;

-- Access tables: users read their own row; admin manages everything
create policy profiles_read on public.profiles for select using (id = auth.uid() or public.has_level(4));
create policy user_access_read on public.user_access for select
  using (public.has_level(4) or email = (select p.email from public.profiles p where p.id = auth.uid()));
create policy user_access_admin on public.user_access for all using (public.has_level(4)) with check (public.has_level(4));
create policy allowed_domains_admin on public.allowed_domains for all using (public.has_level(4)) with check (public.has_level(4));

-- Master data: any signed-in user reads; admin writes
do $$
declare t text;
begin
  foreach t in array array['departments', 'people', 'contract_types', 'action_sla'] loop
    execute format('create policy %I_read on public.%I for select using (public.has_level(1))', t, t);
    execute format('create policy %I_admin_write on public.%I for all using (public.has_level(4)) with check (public.has_level(4))', t, t);
  end loop;
end $$;

-- Contracts: confidential rows only for level 3+ ; writes for level 2+ ; delete admin only
create policy contracts_read on public.contracts for select
  using (public.has_level(1) and (access_level = 'Normal' or public.has_level(3)));
create policy contracts_insert on public.contracts for insert
  with check (public.has_level(2) and (access_level = 'Normal' or public.has_level(3)));
create policy contracts_update on public.contracts for update
  using (public.has_level(2) and (access_level = 'Normal' or public.has_level(3)));
create policy contracts_delete on public.contracts for delete using (public.has_level(4));

-- Logs follow the visibility of their contract
create policy logs_read on public.contract_logs for select
  using (exists (select 1 from public.contracts c where c.id = contract_id));
create policy logs_insert on public.contract_logs for insert
  with check (public.has_level(2) and exists (select 1 from public.contracts c where c.id = contract_id));
create policy logs_admin on public.contract_logs for all using (public.has_level(4)) with check (public.has_level(4));

-- Due date requests: level 2+ create; admin decides
create policy ddr_read on public.due_date_requests for select
  using (exists (select 1 from public.contracts c where c.id = contract_id));
create policy ddr_insert on public.due_date_requests for insert with check (public.has_level(2));
create policy ddr_admin on public.due_date_requests for update using (public.has_level(4));
