create or replace function public.master_row_key(tbl text, r jsonb)
returns text language sql immutable as $$
  select case tbl
    when 'departments' then r ->> 'name'
    when 'people' then r ->> 'name'
    when 'action_sla' then r ->> 'action'
    when 'contract_types' then concat_ws(' | ', r ->> 'classification', r ->> 'type', nullif(r ->> 'sub_type', ''))
    when 'contract_templates' then coalesce(r ->> 'selection_label', r ->> 'name')
    when 'log_view_columns' then concat_ws(' / ', r ->> 'section', r ->> 'key')
    else r ->> 'id' end
$$;

create or replace function public.current_editor()
returns text language sql stable security definer set search_path = public as $$
  select coalesce((select p.email from public.profiles p where p.id = auth.uid()), 'SQL Editor')
$$;

-- Before a write: mark rows changed by hand (not by Import) as locked, with who and when
create or replace function public.master_track()
returns trigger language plpgsql set search_path = public as $$
begin
  if coalesce(current_setting('app.importing', true), 'off') = 'on' then
    if tg_op = 'UPDATE' then
      new.locked := old.locked; new.edited_by := old.edited_by; new.edited_at := old.edited_at;
    end if;
    return new;
  end if;
  if tg_op = 'UPDATE' and (to_jsonb(new) - array['locked', 'edited_by', 'edited_at']) = (to_jsonb(old) - array['locked', 'edited_by', 'edited_at']) then
    return new; -- only the lock was changed
  end if;
  new.edited_by := public.current_editor();
  new.edited_at := now();
  if tg_op = 'INSERT' or new.locked is not distinct from old.locked then
    new.locked := true;
  end if;
  return new;
end $$;

-- After a write: one history entry (unchanged rows are not logged)
create or replace function public.master_audit_log()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  b jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  a jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
begin
  if tg_op = 'UPDATE' and (a - array['edited_by', 'edited_at']) = (b - array['edited_by', 'edited_at']) then
    return null;
  end if;
  insert into public.master_audit (table_name, row_key, action, source, changed_by, before, after)
  values (tg_table_name, public.master_row_key(tg_table_name, coalesce(a, b)), lower(tg_op),
    case when coalesce(current_setting('app.importing', true), 'off') = 'on' then 'import' else 'manual' end,
    public.current_editor(), b, a);
  return null;
end $$;

-- A row still in use cannot be deleted
create or replace function public.master_guard_delete()
returns trigger language plpgsql security definer set search_path = public as $$
declare n int := 0;
begin
  if tg_table_name = 'departments' then
    select (select count(*) from contracts where department = old.name) + (select count(*) from people where department = old.name)
         + (select count(*) from user_access where department = old.name) + (select count(*) from contract_templates where department = old.name) into n;
  elsif tg_table_name = 'people' then
    select (select count(*) from contracts where old.name in (owner, station_from, station_to))
         + (select count(*) from contract_logs where old.name in (from_person, to_person)) into n;
  elsif tg_table_name = 'contract_types' then
    -- contracts point at the Type of Contract; deleting one sub type is fine while another row keeps that type
    if not exists (select 1 from contract_types t where t.type = old.type and t.id <> old.id) then
      select count(*) from contracts where type = old.type into n;
    end if;
  elsif tg_table_name = 'action_sla' then
    select count(*) from contract_logs where action = old.action into n;
  end if;
  if n > 0 then
    raise exception '% "%" is still used by % record(s). Set Active off instead of deleting.',
      tg_table_name, public.master_row_key(tg_table_name, to_jsonb(old)), n;
  end if;
  return old;
end $$;

do $$
declare t text;
begin
  foreach t in array array['departments', 'people', 'contract_types', 'action_sla', 'contract_templates', 'log_view_columns'] loop
    execute format('drop trigger if exists %I_track on public.%I', t, t);
    execute format('create trigger %I_track before insert or update on public.%I for each row execute function public.master_track()', t, t);
    execute format('drop trigger if exists %I_audit on public.%I', t, t);
    execute format('create trigger %I_audit after insert or update or delete on public.%I for each row execute function public.master_audit_log()', t, t);
    execute format('drop trigger if exists %I_guard_delete on public.%I', t, t);
    execute format('create trigger %I_guard_delete before delete on public.%I for each row execute function public.master_guard_delete()', t, t);
  end loop;
end $$;

